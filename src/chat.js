function decompose(prompt, agent) {
  const lower = prompt.toLowerCase();
  const steps = [{ id: "analyze", label: "Analyze the request", agent: "master-orchestrator" }];
  const add = (id, label, agentId) => steps.push({ id, label, agent: agentId });
  if (/(website|web app|application|app|landing|page|ui|dashboard)/.test(lower)) {
    add("design", "Design the interface and structure", "ui-ux");
    add("frontend", "Draft frontend code", "frontend");
  }
  if (/(database|schema|sql|table|model)/.test(lower)) add("database", "Design the data model", "database");
  if (/(api|endpoint|backend|server)/.test(lower)) add("api", "Define API endpoints", "api");
  if (/(python|script|function|debug|bug|code|analysis)/.test(lower)) add("code", "Write and check the code", "coding");
  if (/(security|vulnerab|secret|xss)/.test(lower)) add("security", "Review security", "security");
  if (steps.length === 1) add("answer", `Prepare an answer with the ${agent.name}`, agent.id);
  add("review", "Review and summarise results", "independent-reviewer");
  return steps.slice(0, 8);
}

