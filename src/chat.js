function localReply({ prompt, agent, attachments = [] }) {
  const lower = prompt.toLowerCase();
  const parts = [];
  parts.push(`**${agent.name}** is answering in *local deterministic mode* (no AI provider is connected, so this is a template-based response, not generated by a model).`);
  if (attachments.length) {
    parts.push(`Attached: ${attachments.map((file) => `\`${file.name}\``).join(", ")}.`);
    const textFile = attachments.find((file) => typeof file.content === "string" && file.content);
    if (textFile) {
      const extension = textFile.name.split(".").pop() || "text";
      parts.push(`Beginning of \`${textFile.name}\`:\n\n\`\`\`${extension}\n${textFile.content.slice(0, 600)}\n\`\`\``);
    }
  }
  if (/to-?do/.test(lower)) {
    parts.push("Here is a complete, dependency-free **To-Do list** you can save into your workspace:");
    parts.push(TODO_APP);
  } else if (/python/.test(lower) && /(data|analysis|csv)/.test(lower)) {
    parts.push("A small standard-library **data analysis** script:");
    parts.push(PYTHON_ANALYSIS);
  } else if (/(database|schema)/.test(lower)) {
    parts.push("A starter **database schema** with constraints and an index:");
    parts.push(SCHEMA);
  } else if (/(debug|bug|error|fix)/.test(lower)) {
    parts.push(DEBUG);
  } else {
    parts.push(`I understood your request as:\n\n> ${prompt.slice(0, 300)}\n\nConnect an AI provider in **Settings → Connect an AI provider** for model-generated answers. Until then I can break the work into tasks, review code you attach, and use the Blueprint Editor, Workspace, and Git tools.`);
  }
  parts.push(`_Next:_ use **Save to workspace** on a code block, then run **Review** in the Workspace for the Refactoring and Security agents.`);
  return parts.join("\n\n");
}

function* chunk(text, size = 12) {
  for (let index = 0; index < text.length; index += size) yield text.slice(index, index + size);
}

function buildMessages({ agent, history, prompt, attachments }) {
  const attachmentText = attachments
    .filter((file) => typeof file.content === "string" && file.content)
    .map((file) => `File ${file.name}:\n${file.content.slice(0, 20000)}`).join("\n\n");
  return [
    { role: "system", content: agent.systemInstructions },
    ...history.slice(-20).map((message) => ({ role: message.role === "assistant" ? "assistant" : "user", content: message.content.slice(0, 8000) })),
    { role: "user", content: attachmentText ? `${prompt}\n\n${attachmentText}` : prompt }
  ];
}

